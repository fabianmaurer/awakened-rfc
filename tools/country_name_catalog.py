def read_catalog():
    result = {}
    code = None
    values = []
    for line in CATALOG.strip().splitlines():
        if '|' not in line:
            if code is not None:
                if len(values) != len(FAMILIES):
                    raise ValueError('Incomplete country catalogue: ' + code)
                result[code] = dict(zip(FAMILIES, values))
            code, values = line.strip(), []
        else:
            values.append(tuple(part.strip() for part in line.split('|')))
    if len(values) != len(FAMILIES):
        raise ValueError('Incomplete country catalogue: ' + code)
    result[code] = dict(zip(FAMILIES, values))
    return result


COUNTRY_NAMES = read_catalog()

