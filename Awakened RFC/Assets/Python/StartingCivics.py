DEFAULTS = ("TRIBAL_SYSTEM", "DESPOTISM", "SELF_SUFFICIENCY", "WARRIOR_SOCIETY", "ANCESTOR_CULT")
FALLBACKS = (
    ("MONARCHY", "TRIBAL_SYSTEM"),
    ("DESPOTISM",),
    ("SLAVERY", "SELF_SUFFICIENCY"),
    ("MILITIA", "WARRIOR_SOCIETY"),
    ("STATE_RELIGION", "ANCESTOR_CULT"),
)


def apply(iPlayer):
    # Resolve infos here, never during module import before XML is available.
    gc = CyGlobalContext()
    player = gc.getPlayer(iPlayer)
    civType = player.getCivilizationType()
    if civType < 0:
        return
    profile = PROFILES.get(gc.getCivilizationInfo(civType).getType(), DEFAULTS)
    for iColumn in range(len(profile)):
        for name in (profile[iColumn],) + FALLBACKS[iColumn]:
            civic = gc.getInfoTypeForString("CIVIC_" + name)
            if civic >= 0 and player.canDoCivics(civic):
                option = gc.getCivicInfo(civic).getCivicOptionType()
                if player.getCivics(option) != civic:
                    player.setCivics(option, civic)
                break
